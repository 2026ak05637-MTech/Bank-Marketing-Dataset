import pandas as pd
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score, roc_auc_score, matthews_corrcoef

def get_metrics(model_name, model, X_eval, y_true):
    """Helper to consistently compute evaluation metrics for both scaled and unscaled models."""
    y_pred = model.predict(X_eval)

    # Handle models that support probability estimations for ROC AUC
    if hasattr(model, "predict_proba"):
        y_prob = model.predict_proba(X_eval)[:, 1]
    elif hasattr(model, "decision_function"):
        y_prob = model.decision_function(X_eval)
    else:
        y_prob = y_pred

    return {
        "Model": model_name,
        "Accuracy": accuracy_score(y_true, y_pred),
        "Precision (Class 1)": precision_score(y_true, y_pred, zero_division=0),
        "Recall (Class 1)": recall_score(y_true, y_pred, zero_division=0),
        "F1-Score (Class 1)": f1_score(y_true, y_pred, zero_division=0),
        "ROC AUC": roc_auc_score(y_true, y_prob),
        "MCC": matthews_corrcoef(y_true, y_pred)
    }

# Calculate metrics for all models based on their corresponding correct datasets
metrics_list = [
    get_metrics("Logistic Regression (Balanced)", lr, X_test_scaled, y_test),
    get_metrics("Decision Tree (Balanced)", dt, X_test, y_test),
    get_metrics("K-Nearest Neighbors (k=5)", knn, X_test_scaled, y_test),
    get_metrics("Naive Bayes", nb, X_test_scaled, y_test),
    get_metrics("Support Vector Classifier (Balanced)", svm, X_test_scaled, y_test)
]

# Compile into a DataFrame for comparison
comparison_df = pd.DataFrame(metrics_list)
display(comparison_df.round(4))

def evaluate_model(model, X_eval):
    y_pred = model.predict(X_eval)

    if hasattr(model, "predict_proba"):
        y_prob = model.predict_proba(X_eval)[:, 1]
    elif hasattr(model, "decision_function"):
        y_prob = model.decision_function(X_eval)
    else:
        y_prob = y_pred

    return {
        "Accuracy": accuracy_score(y_test, y_pred),
        "AUC": roc_auc_score(y_test, y_prob),
        "Precision": precision_score(y_test, y_pred, zero_division=0),
        "Recall": recall_score(y_test, y_pred, zero_division=0),
        "F1": f1_score(y_test, y_pred, zero_division=0),
        "MCC": matthews_corrcoef(y_test, y_pred)
    }

# Map each model to its correct test dataset to guarantee evaluation accuracy
results = {
    "Logistic Regression": evaluate_model(lr, X_test_scaled),
    "Decision Tree": evaluate_model(dt, X_test),
    "KNN": evaluate_model(knn, X_test_scaled),
    "Naive Bayes": evaluate_model(nb, X_test_scaled),
    "SVM": evaluate_model(svm, X_test_scaled)
}

results_df = pd.DataFrame(results).T
